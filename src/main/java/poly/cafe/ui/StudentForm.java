    void loadData() {
        List<Student> listStudent = studentDAOImpl.findAll();
        System.out.println(listStudent.size());
        DefaultTableModel table = (DefaultTableModel) tblStudent.getModel();
        table.setRowCount(0);
        listStudent.forEach(item -> {
            Object[] rowData = {
                item.getId(),
                item.getClassName(),
                item.getEmail(),
                item.getFullName(),
                item.getGender(),
                item.getMajor(),
                item.getPhone(),
                item.getStudentCode()
            };
            System.out.println(rowData.toString());
            table.addRow(rowData);
        });
    }

