    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // lay thong tin tren form
        String className = this.className.getText();
        String email = this.email.getText();
        String fullName = this.fullName.getText();
        String gender = "";
        if (this.female.isSelected()) {
            gender = this.female.getText();
        } else {
            gender = this.male.getText();
        }
        String major = cboMajor.getSelectedItem().toString();
        String phone = this.phone.getText();
        String studentCode = this.studentCode.getText();
        Student student = new Student(className, email, fullName, gender, major, phone, studentCode);
        studentDAOImpl.create(student);

        // load lai giao dien
        loadData();
        clearForm();
    }//GEN-LAST:event_jButton1ActionPerformed

