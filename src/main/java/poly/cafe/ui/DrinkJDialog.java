    @Override
    public void fillToTable() {
        DefaultTableModel model = (DefaultTableModel) tblDrinks.getModel();
        model.setRowCount(0);
        Category category = categories.get(cbCategories.getSelectedIndex());
        items = dao.findByCategoryName(category.getName());
        items.forEach(item -> {
            Object[] rowData = {
                item.getId(),
                item.getName(),
                item.getUnitPrice(),
                item.getDiscount(),
                item.getAvailable(),
                false
            };
            model.addRow(rowData);
        });

    }

