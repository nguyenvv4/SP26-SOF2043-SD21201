    @Override
    public void fillCategories() {
        // code hien thi danh sach loai do uong len table
        DefaultComboBoxModel cboModel = (DefaultComboBoxModel) cbCategories.getModel();
        cboModel.removeAllElements();

        DefaultTableModel tblModel = (DefaultTableModel) tblDrinks.getModel();
        tblModel.setRowCount(0);

        CategoryDAO cdao = new CategoryDAOImpl();
        categories = cdao.findAll();

        categories.forEach(category -> {
            cboModel.addElement(category.getName());
        });
//        tblCategories.setRowSelectionInterval(0, 0);
    }

